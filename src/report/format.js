'use strict';

/** Report renderers. All are pure functions of the report → deterministic. */

const { DIMENSIONS } = require('../engine/dread');

const DREAD_ABBR = { damage: 'D', reproducibility: 'R', exploitability: 'E', affectedUsers: 'A', discoverability: 'Di' };

function toJSON(report) {
  return `${JSON.stringify(report, null, 2)}\n`;
}

function vector(v) {
  return DIMENSIONS.map((d) => `${DREAD_ABBR[d]}${v[d]}`).join(' ');
}

function scoringLabel(scoring) {
  if (scoring.method === 'risk') return 'DREAD likelihood × impact, OWASP severity matrix';
  if (scoring.method === 'mean') return 'DREAD arithmetic mean';
  return `DREAD weighted (${DIMENSIONS.map((d) => `${DREAD_ABBR[d]}=${scoring.weights[d]}`).join(', ')})`;
}

function toMarkdown(report) {
  const { model, summary, findings, scoring, tool } = report;
  const lines = [];
  lines.push(`# Threat Model Report — ${model.name}`, '');
  lines.push(`Generated by ${tool.name} ${tool.version} (rule base ${tool.ruleBaseVersion}). Scoring: ${scoringLabel(scoring)}.`, '');
  lines.push(`Model hash: \`${model.sha256}\``, '');
  lines.push('## Summary', '');
  lines.push(`${summary.total} findings across ${summary.coverage.strideCategoriesHit}/6 STRIDE categories `
    + `(${summary.coverage.rulesTriggered}/${summary.coverage.rulesEvaluated} rules triggered).`, '');
  lines.push('| Severity | Count |', '| --- | --- |');
  for (const [s, n] of Object.entries(summary.bySeverity)) lines.push(`| ${s} | ${n} |`);
  lines.push('', '| STRIDE category | Count |', '| --- | --- |');
  for (const [c, n] of Object.entries(summary.byCategory)) lines.push(`| ${c} | ${n} |`);
  lines.push('', '## Findings', '');
  lines.push('| # | Score | Severity | Rule | Category | Target | Title |', '| --- | --- | --- | --- | --- | --- | --- |');
  findings.forEach((f, i) => {
    lines.push(`| ${i + 1} | ${f.score.toFixed(1)} | ${f.severity} | ${f.ruleId} | ${f.category} | ${f.target.name} | ${f.title} |`);
  });
  lines.push('');
  findings.forEach((f, i) => {
    lines.push(`### ${i + 1}. ${f.title} — ${f.target.name}`, '');
    lines.push(`**${f.severity} (${f.score.toFixed(1)})** · ${f.category} · rule ${f.ruleId} · ${f.target.type} \`${f.target.id}\``, '');
    lines.push(f.description, '');
    lines.push(`DREAD base ${vector(f.dread.base)} → final ${vector(f.dread.final)}`);
    if (f.dread.risk) {
      const r = f.dread.risk;
      lines.push(`Likelihood ${r.likelihood} (${r.likelihoodLevel}) × impact ${r.impact} (${r.impactLevel})`);
    }
    for (const a of f.dread.adjustments) lines.push(`- ${a.reason}`);
    lines.push('', '**Remediation**', '');
    for (const r of f.remediation) lines.push(`- ${r}`);
    if (f.references.length) lines.push('', `References: ${f.references.join(', ')}`);
    lines.push('');
  });
  return `${lines.join('\n')}\n`;
}

function toText(report) {
  const { model, summary, findings, scoring } = report;
  const out = [];
  out.push(`${model.name} — ${summary.total} findings (${scoringLabel(scoring)})`);
  out.push(Object.entries(summary.bySeverity).map(([s, n]) => `${s}: ${n}`).join('  '));
  out.push('');
  for (const f of findings) {
    out.push(`${f.score.toFixed(1).padStart(4)}  ${f.severity.padEnd(8)} ${f.ruleId}  ${f.title} — ${f.target.name}`);
  }
  return `${out.join('\n')}\n`;
}

const FORMATTERS = { json: toJSON, md: toMarkdown, markdown: toMarkdown, text: toText };

function render(report, format = 'json') {
  const fn = FORMATTERS[format];
  if (!fn) throw new Error(`Unknown format "${format}" (expected json, md or text)`);
  return fn(report);
}

module.exports = { render, toJSON, toMarkdown, toText };

'use strict';

/**
 * Generates docs/model-reference.md: every component type, control and data
 * flow field, with the rules that read each one. Generated from the same
 * sources as the JSON Schema and the rule base so it cannot go stale
 * (a test checks the committed file matches).
 */

const { COMPONENT_TYPES, KINDS } = require('./architecture');
const { COMPONENT_TYPE_DOCS, PROPERTY_DOCS, FLOW_DOCS, DATA_CLASSIFICATION_DOCS } = require('./docs');

// Facts the engine derives from a property, so rules that read the derived fact count too.
const DERIVED = {
  publicFacing: ['internetExposed', 'system.hasPublicFacing'],
  waf: ['system.hasEdgeProtection'],
  dataClassification: ['system.hasSensitiveData'],
};

function factsByRule(ruleBase) {
  const out = new Map();
  const walk = (p, set) => {
    if (!p || typeof p !== 'object') return;
    if (p.all) p.all.forEach((x) => walk(x, set));
    else if (p.any) p.any.forEach((x) => walk(x, set));
    else if (p.not) walk(p.not, set);
    else if (p.fact) set.add(p.fact);
  };
  for (const r of ruleBase.rules) { const s = new Set(); walk(r.when, s); out.set(r.id, s); }
  return out;
}

function rulesReading(facts, names) {
  return [...facts].filter(([, set]) => names.some((n) => set.has(n))).map(([id]) => id).sort();
}

function buildReference(ruleBase) {
  const facts = factsByRule(ruleBase);
  const L = [];
  L.push('# Model reference', '');
  L.push('<!-- Generated by `npm run build:schema` from src/schema/docs.js and the rule base. Do not edit by hand. -->', '');
  L.push(`Rule base ${ruleBase.version}. For how to write a model, see the [modelling guide](modelling-guide.md).`, '');

  L.push('## Component types', '', '| Type | Drawn as | Use for |', '| --- | --- | --- |');
  const shape = { actor: 'external entity', external: 'external entity', datastore: 'data store', process: 'process', edge: 'process' };
  for (const t of COMPONENT_TYPES) L.push(`| \`${t}\` | ${shape[KINDS[t]]} | ${COMPONENT_TYPE_DOCS[t]} |`);

  L.push('', '## Component controls (`properties`)', '');
  L.push('Anything you leave out counts as **missing**. Unknown names produce a warning with a suggested fix.', '');
  L.push('| Property | Meaning | Checked by rules |', '| --- | --- | --- |');
  for (const [p, doc] of Object.entries(PROPERTY_DOCS)) {
    const ids = rulesReading(facts, [`component.properties.${p}`, ...(DERIVED[p] || [])]);
    L.push(`| \`${p}\` | ${doc} | ${ids.join(', ') || '–'} |`);
  }

  L.push('', '## Data flow fields', '', '| Field | Meaning | Checked by rules |', '| --- | --- | --- |');
  for (const [k, doc] of Object.entries(FLOW_DOCS)) {
    const derived = k === 'protocol' ? ['flow.encrypted'] : k === 'dataClassification' ? ['sensitive'] : [];
    const ids = rulesReading(facts, [`flow.${k}`, ...derived]);
    L.push(`| \`${k}\` | ${doc} | ${ids.join(', ') || '–'} |`);
  }

  L.push('', '## Data classification', '', '| Value | Meaning |', '| --- | --- |');
  for (const [k, doc] of Object.entries(DATA_CLASSIFICATION_DOCS)) L.push(`| \`${k}\` | ${doc} |`);

  L.push('', '## Rules', '', '| Rule | STRIDE category | Applies to | Threat |', '| --- | --- | --- | --- |');
  for (const r of ruleBase.rules) L.push(`| ${r.id} | ${r.category} | ${r.appliesTo === 'dataFlow' ? 'data flow' : r.appliesTo} | ${r.title} |`);
  return `${L.join('\n')}\n`;
}

module.exports = { buildReference };
